def append_offers():
    with open("js/store-data.js", "r", encoding="utf-8") as f:
        src = f.read()
    
    # We want to insert NEW_OFFERS right before the closing of offers: [ ... ]
    # Find offers: [
    idx_offers = src.find("offers: [")
    if idx_offers == -1:
        raise ValueError("Could not find offers: [ in js/store-data.js")
    
    # Find the matching closing bracket for offers: [ ... ]
    # It ends right before `  };` or `  window.TSB_STORE_DATA`
    idx_close = src.rfind("    ]")
    if idx_close == -1:
        idx_close = src.rfind("]")
    
    existing_offers_str = src[idx_offers+len("offers: ["):idx_close].strip()
    
    # Format new offers cleanly
    new_offers_lines = []
    for o in NEW_OFFERS:
        steps_json = json.dumps(o["steps"], ensure_ascii=False)
        tnc_json = json.dumps(o["tnc"], ensure_ascii=False)
        code_str = f'"{o["code"]}"' if o["code"] else "null"
        top_str = "true" if o["top"] else "false"
        
        entry = f"""      {{ id: "{o['id']}", brand: "{o['brand']}", cat: "{o['cat']}", logo: "{o['logo']}", fit: "{o['fit']}", bg: "{o['bg']}",
        tag: "{o['tag']}", value: "{o['value']}", worth: "{o['worth']}", top: {top_str},
        title: "{o['title']}",
        desc: "{o['desc']}",
        code: {code_str}, url: "{o['url']}",
        steps: {steps_json},
        tnc: {tnc_json} }}"""
        new_offers_lines.append(entry)
    
    combined = existing_offers_str + ",\n\n      /* ───────────── 🚀 EXCLUSIVE PRO & STUDENT HUBS ───────────── */\n" + ",\n\n".join(new_offers_lines)
    
    new_src = src[:idx_offers+len("offers: [\n")] + combined + "\n    " + src[idx_close:]
    with open("js/store-data.js", "w", encoding="utf-8") as f:
        f.write(new_src)
    print("js/store-data.js updated with 51 new dream offers!")

if __name__ == "__main__":
    append_offers()
